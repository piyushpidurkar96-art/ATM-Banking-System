CREATE TABLE TRANSACTION_MASTER (TRANSACTION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
								ACCOUNT_ID        NUMBER NOT NULL,
								CARD_ID           NUMBER NOT NULL,
								ATM_ID            NUMBER,
								TYPE_ID           NUMBER NOT NULL,
								TRANSACTION_REF   VARCHAR2(50) UNIQUE,
								TRANSACTION_DATE  TIMESTAMP DEFAULT SYSTIMESTAMP,
								TRANSACTION_AMOUNT NUMBER(12,2) DEFAULT 0,
								BALANCE_BEFORE    NUMBER(12,2),
								BALANCE_AFTER     NUMBER(12,2),
								TRANSACTION_STATUS VARCHAR2(20) DEFAULT 'SUCCESS',
								REMARKS           VARCHAR2(200),

								CONSTRAINT FK_TXN_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
								REFERENCES ACCOUNT_MASTER(ACCOUNT_ID),

								CONSTRAINT FK_TXN_CARD FOREIGN KEY (CARD_ID)
								REFERENCES CARD_MASTER(CARD_ID),

								CONSTRAINT FK_TXN_ATM FOREIGN KEY (ATM_ID)
								REFERENCES ATM_MASTER(ATM_ID),

								CONSTRAINT FK_TXN_TYPE FOREIGN KEY (TYPE_ID)
								REFERENCES TRANSACTION_TYPE(TYPE_ID),

								CONSTRAINT CHK_TXN_AMOUNT CHECK (TRANSACTION_AMOUNT >= 0),
								CONSTRAINT CHK_TXN_STATUS CHECK (TRANSACTION_STATUS IN ('SUCCESS', 'FAILED', 'PENDING', 'REVERSED'))
								);
                                
