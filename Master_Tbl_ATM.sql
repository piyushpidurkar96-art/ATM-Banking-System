CREATE TABLE ACCOUNT_MASTER (ACCOUNT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
							CIN              VARCHAR2(20) NOT NULL,
							BRANCH_ID        NUMBER NOT NULL,
							ACCOUNT_NUMBER   VARCHAR2(20) UNIQUE NOT NULL,
							ACCOUNT_TYPE     VARCHAR2(20) NOT NULL,
							OPENING_DATE     DATE DEFAULT SYSDATE,
							OPENING_BALANCE  NUMBER(12,2) DEFAULT 0,
							CURRENT_BALANCE  NUMBER(12,2) DEFAULT 0,
							ACCOUNT_STATUS   VARCHAR2(20) DEFAULT 'ACTIVE',
							CREATED_DATE     DATE DEFAULT SYSDATE,

							CONSTRAINT FK_ACC_CUSTOMER FOREIGN KEY (CIN)
							REFERENCES CUSTOMER_MASTER(CIN),

							CONSTRAINT FK_ACC_BRANCH FOREIGN KEY (BRANCH_ID)
							REFERENCES BRANCH_MASTER(BRANCH_ID),

							CONSTRAINT CHK_ACC_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS', 'CURRENT')),

							CONSTRAINT CHK_ACC_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'INACTIVE', 'BLOCKED', 'CLOSED')),

							CONSTRAINT CHK_ACC_BALANCE CHECK (OPENING_BALANCE >= 0 AND CURRENT_BALANCE >= 0)
							);     
                            
                            
CREATE TABLE CARD_MASTER (CARD_ID		 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
						  ACCOUNT_ID       NUMBER NOT NULL,
						  CARD_NUMBER      VARCHAR2(64) UNIQUE NOT NULL,
						  CARD_TYPE        VARCHAR2(20),
						  CARD_EXPIRY_DATE DATE NOT NULL,
						  PIN_HASH         VARCHAR2(255) NOT NULL,
						  CARD_STATUS      VARCHAR2(20) DEFAULT 'ACTIVE',
						  ISSUE_DATE       DATE DEFAULT SYSDATE,
						  CREATED_DATE     DATE DEFAULT SYSDATE,
						  CONSTRAINT FK_CARD_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
						  REFERENCES ACCOUNT_MASTER(ACCOUNT_ID),
						  CONSTRAINT CHK_CARD_TYPE CHECK (CARD_TYPE IN ('VISA', 'MASTERCARD', 'RUPAY')),
						  CONSTRAINT CHK_CARD_STATUS CHECK (CARD_STATUS IN ('ACTIVE', 'BLOCKED', 'EXPIRED', 'CLOSED'))
						  );             
                          
CREATE TABLE ATM_MASTER (ATM_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
						ATM_CODE        VARCHAR2(20) UNIQUE NOT NULL,
						ATM_LOCATION    VARCHAR2(200),
						CITY            VARCHAR2(50),
						STATE           VARCHAR2(50),
						BRANCH_ID       NUMBER,
						ATM_STATUS      VARCHAR2(20) DEFAULT 'ACTIVE',
						CREATED_DATE    DATE DEFAULT SYSDATE,
						CONSTRAINT FK_ATM_BRANCH FOREIGN KEY (BRANCH_ID)
						REFERENCES BRANCH_MASTER(BRANCH_ID),
						CONSTRAINT CHK_ATM_STATUS CHECK (ATM_STATUS IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
						);	                                                    
                        
